"""
ℹ️ Demo of four common Python data types:
String, Integer, Float, and Boolean.
"""

# ℹ️ A String stores text inside quotation marks.
string_of_characters = "Is this the real life?"

# ℹ️ An Integer stores a whole number without a decimal point.
just_an_int = 42

# ℹ️ A Float stores a number with a decimal point.
soda_in_ice_cream = 3.1415927

# ℹ️ A Boolean stores one of two values: True or False.
reality_check = False

# 💡 F-strings insert variables into text using curly braces.
# ℹ️ The \n escape sequence creates a new line.
# ℹ️ The \t escape sequence creates a tab.
print(f"\n\tA String \t=\t {string_of_characters}\n")
print(f"\n\tAn Integer \t=\t {just_an_int}\n")
print(f"\n\tA Float \t=\t {soda_in_ice_cream}\n")
print(f"\n\tA Boolean \t=\t {reality_check}\n")
